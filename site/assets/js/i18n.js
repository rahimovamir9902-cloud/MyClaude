/* -------------------------------------------------------------------------
   Engine
   ---------------------------------------------------------------------- */
(function () {
  var STORE = 'oa-lang';
  var cache = new WeakMap();   // node -> original English string

  function nodes() {
    return document.querySelectorAll('[data-i18n], [data-i18n-html]');
  }

  function apply(lang) {
    var dict = window.I18N[lang];

    nodes().forEach(function (el) {
      var html = el.hasAttribute('data-i18n-html');
      var key = el.getAttribute(html ? 'data-i18n-html' : 'data-i18n');
      var prop = html ? 'innerHTML' : 'textContent';

      if (!cache.has(el)) cache.set(el, el[prop]);

      if (dict && dict[key] != null) {
        el[prop] = dict[key];
      } else {
        el[prop] = cache.get(el);      // back to English
      }
    });

    document.documentElement.lang = lang;

    document.querySelectorAll('.langswitch button').forEach(function (b) {
      var on = b.dataset.lang === lang;
      b.classList.toggle('is-active', on);
      b.setAttribute('aria-pressed', String(on));
    });

    try { localStorage.setItem(STORE, lang); } catch (e) {}

    // Config values and prices live inside some translated strings, so they
    // have to be re-injected after every swap.
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: lang } }));
  }

  function saved() {
    var v;
    try { v = localStorage.getItem(STORE); } catch (e) {}
    if (v) return v;
    // First visit: follow the browser, but only into a language we have.
    var nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return window.I18N[nav] ? nav : 'en';
  }

  window.setLang = apply;

  document.addEventListener('DOMContentLoaded', function () {
    document.querySelectorAll('.langswitch button').forEach(function (b) {
      b.addEventListener('click', function () { apply(b.dataset.lang); });
    });
    apply(saved());
  });
})();
